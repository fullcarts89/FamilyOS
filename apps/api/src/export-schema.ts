import { z } from 'zod';

/** Shape of a household export (format version 1). Used to validate round-trips in tests. */
const Timestamp = z.union([z.string(), z.date()]).transform((v) => new Date(v).toISOString());

export const HouseholdExportSchema = z.object({
  formatVersion: z.literal(1),
  exportedAt: z.string(),
  scope: z.literal('visible_to_member'),
  household: z.object({
    id: z.uuid(),
    name: z.string(),
    timezone: z.string(),
    createdAt: Timestamp,
  }),
  members: z.array(
    z.object({
      id: z.uuid(),
      displayName: z.string(),
      role: z.enum(['owner', 'adult', 'caregiver', 'child', 'pet']),
      status: z.enum(['active', 'removed']),
      color: z.string().regex(/^#[0-9A-F]{6}$/),
      species: z.string().nullable(),
      note: z.string().nullable(),
      createdAt: Timestamp,
      removedAt: Timestamp.nullable(),
    }),
  ),
  invites: z.array(
    z.object({
      id: z.uuid(),
      email: z.string(),
      role: z.enum(['adult', 'caregiver']),
      expiresAt: Timestamp,
      acceptedAt: Timestamp.nullable(),
      revokedAt: Timestamp.nullable(),
      createdAt: Timestamp,
    }),
  ),
  sources: z.array(
    z.object({
      id: z.uuid(),
      kind: z.string(),
      storageRef: z.string().nullable(),
      createdAt: Timestamp,
    }),
  ),
  workItems: z.array(
    z.object({
      id: z.uuid(),
      type: z.string(),
      title: z.string(),
      description: z.string().nullable(),
      status: z.string(),
      ownerMemberId: z.uuid().nullable(),
      parentId: z.uuid().nullable(),
      dueOn: z.string().nullable(),
      dueAt: Timestamp.nullable(),
      priority: z.number().nullable(),
      visibility: z.enum(['household', 'private']),
      createdByMemberId: z.uuid(),
      recurrenceRuleId: z.uuid().nullable(),
      occurrenceIndex: z.number().nullable(),
      occurrenceOn: z.string().nullable(),
      completedAt: Timestamp.nullable(),
      completedByMemberId: z.uuid().nullable(),
      subjectMemberId: z.uuid().nullable(),
      contactId: z.uuid().nullable(),
      version: z.number(),
      createdAt: Timestamp,
      updatedAt: Timestamp,
    }),
  ),
  recurrenceRules: z.array(
    z.object({
      id: z.uuid(),
      routineId: z.uuid(),
      rule: z.record(z.string(), z.unknown()),
      timezone: z.string(),
      startOn: z.string(),
      localTime: z.string().nullable(),
      rotation: z.array(z.uuid()),
      pausedAt: Timestamp.nullable(),
      generateFrom: z.string(),
      createdAt: Timestamp,
    }),
  ),
  occurrenceExceptions: z.array(
    z.object({
      id: z.uuid(),
      recurrenceRuleId: z.uuid(),
      occurrenceIndex: z.number(),
      kind: z.enum(['skip', 'owner']),
      reason: z.enum(['member', 'paused']).nullable(),
      ownerMemberId: z.uuid().nullable(),
      createdByMemberId: z.uuid().nullable(),
      createdAt: Timestamp,
    }),
  ),
  comments: z.array(
    z.object({
      id: z.uuid(),
      workItemId: z.uuid(),
      authorMemberId: z.uuid(),
      body: z.string(),
      createdAt: Timestamp,
    }),
  ),
  auditEvents: z.array(
    z.object({
      id: z.string(),
      actorMemberId: z.uuid().nullable(),
      entityType: z.string(),
      entityId: z.uuid(),
      action: z.string(),
      payload: z.record(z.string(), z.unknown()),
      createdAt: Timestamp,
    }),
  ),
  events: z.array(
    z.object({
      id: z.uuid(),
      title: z.string(),
      kind: z.string(),
      startsAt: Timestamp,
      endsAt: Timestamp,
      allDay: z.boolean(),
      location: z.string().nullable(),
      notes: z.string().nullable(),
      recurrence: z.record(z.string(), z.unknown()).nullable(),
      recursUntil: z.string().nullable(),
      timezone: z.string(),
      careMemberId: z.uuid().nullable(),
      careAction: z.enum(['drop_off', 'pick_up']).nullable(),
      carePlace: z.string().nullable(),
      sourceCalendarId: z.uuid().nullable(),
      createdByMemberId: z.uuid(),
      version: z.number(),
      createdAt: Timestamp,
      updatedAt: Timestamp,
    }),
  ),
  calendars: z.array(
    z.object({
      id: z.uuid(),
      label: z.string(),
      memberId: z.uuid(),
      urlHint: z.string(),
      color: z.string().nullable(),
      status: z.enum(['pending', 'ok', 'error']),
      lastSyncedAt: Timestamp.nullable(),
      createdAt: Timestamp,
    }),
  ),
  eventMembers: z.array(z.object({ eventId: z.uuid(), memberId: z.uuid() })),
  eventExceptions: z.array(
    z.object({
      id: z.uuid(),
      eventId: z.uuid(),
      occurrenceDate: z.string(),
      kind: z.enum(['skip', 'cover']),
      coverMemberId: z.uuid().nullable(),
      createdByMemberId: z.uuid(),
      createdAt: Timestamp,
    }),
  ),
  contacts: z.array(
    z.object({
      id: z.uuid(),
      name: z.string(),
      category: z.string(),
      role: z.string().nullable(),
      organization: z.string().nullable(),
      phone: z.string().nullable(),
      email: z.string().nullable(),
      address: z.string().nullable(),
      notes: z.string().nullable(),
      forMemberId: z.uuid().nullable(),
      createdByMemberId: z.uuid(),
      version: z.number(),
      createdAt: Timestamp,
      updatedAt: Timestamp,
    }),
  ),
  decisions: z.array(
    z.object({
      id: z.uuid(),
      question: z.string(),
      context: z.string().nullable(),
      dueOn: z.string().nullable(),
      status: z.enum(['open', 'decided', 'dropped']),
      decidedOptionId: z.uuid().nullable(),
      decidedAt: Timestamp.nullable(),
      decidedVia: z.enum(['agreement', 'call']).nullable(),
      decidedByMemberId: z.uuid().nullable(),
      createdByMemberId: z.uuid(),
      version: z.number(),
      createdAt: Timestamp,
    }),
  ),
  decisionOptions: z.array(
    z.object({
      id: z.uuid(),
      decisionId: z.uuid(),
      label: z.string(),
      detail: z.string().nullable(),
      position: z.number(),
    }),
  ),
  decisionVotes: z.array(
    z.object({ decisionId: z.uuid(), memberId: z.uuid(), optionId: z.uuid(), votedAt: Timestamp }),
  ),
  meals: z.array(
    z.object({
      id: z.uuid(),
      onDate: z.string(),
      slot: z.enum(['breakfast', 'lunch', 'dinner']),
      title: z.string(),
      cookMemberId: z.uuid().nullable(),
      notes: z.string().nullable(),
      createdByMemberId: z.uuid(),
      version: z.number(),
      createdAt: Timestamp,
    }),
  ),
  groceryItems: z.array(
    z.object({
      id: z.uuid(),
      name: z.string(),
      detail: z.string().nullable(),
      aisle: z.string(),
      position: z.number(),
      checkedAt: Timestamp.nullable(),
      checkedByMemberId: z.uuid().nullable(),
      addedByMemberId: z.uuid(),
      createdAt: Timestamp,
    }),
  ),
  weeklyPlans: z.array(
    z.object({
      id: z.uuid(),
      weekStart: z.string(),
      notes: z.string().nullable(),
      committedAt: Timestamp.nullable(),
      committedByMemberId: z.uuid().nullable(),
      version: z.number(),
    }),
  ),
  budgetSnapshots: z.array(
    z.object({
      month: z.string(),
      category: z.string(),
      group: z.string().nullable(),
      budgeted: z.string().nullable(),
      actual: z.string().nullable(),
      importedAt: Timestamp,
      importedByMemberId: z.uuid(),
    }),
  ),
  /** Uploaded files arrive in M5; the manifest lists them by storage key. */
  files: z.array(z.object({ sourceId: z.uuid(), storageRef: z.string() })),
});

export type HouseholdExport = z.infer<typeof HouseholdExportSchema>;
